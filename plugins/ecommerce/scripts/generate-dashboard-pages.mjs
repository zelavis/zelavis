/**
 * Inlines the plugin's dashboard pages as page assets.
 *
 * The menu used to point at `bundle: "dashboard"`, which resolves through the
 * bundle store — and nothing ever uploaded these files into one, so every page
 * answered "Service asset not found" while the plugin looked installed.
 *
 * `pageAssets` is the mechanism for a service that ships its own page bytes:
 * no upload step, no install-time copying, and the same route serves them. The
 * files stay editable HTML on disk and this turns them into a module.
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const source = "dashboard";
const target = join("src", "generated", "dashboard-pages.ts");

const files = (await readdir(source)).filter((name) => name.endsWith(".html")).sort();
if (files.length === 0) {
  throw new Error(`No dashboard pages found in ${source}/.`);
}

const entries = await Promise.all(
  files.map(async (name) => {
    const body = await readFile(join(source, name), "utf8");
    return `  ${JSON.stringify(name)}: Object.freeze({\n    contentType: "text/html; charset=utf-8",\n    body: ${JSON.stringify(body)},\n  }),`;
  }),
);

await writeFile(
  target,
  `// Generated by scripts/generate-dashboard-pages.mjs. Edit dashboard/*.html.\n` +
    `export const ecommerceDashboardPages = Object.freeze({\n${entries.join("\n")}\n});\n`,
  "utf8",
);
