/**
 * Generates the stylesheet framed service pages link against.
 *
 * A service page renders in its own document, so it inherits nothing from the
 * dashboard. Rather than let every service invent its own colours, the design
 * tokens are extracted from the dashboard's own stylesheet — the same source,
 * so the two cannot drift — and shipped with a small base layer that makes a
 * plain HTML page look like it belongs.
 *
 * Deliberately not the whole Tailwind build: a service page should get the
 * design system's vocabulary, not the dashboard's component classes, which are
 * an implementation detail the dashboard is free to change.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const source = fileURLToPath(new URL("../app/styles.css", import.meta.url));
const output = fileURLToPath(
  new URL("../src/generated/service-page-styles.ts", import.meta.url),
);

const css = readFileSync(source, "utf8");

function extractBlock(selector) {
  const start = css.indexOf(`${selector} {`);
  if (start < 0) {
    throw new Error(`app/styles.css no longer contains a "${selector}" block.`);
  }
  const end = css.indexOf("\n}", start);
  if (end < 0) {
    throw new Error(`The "${selector}" block in app/styles.css is unterminated.`);
  }
  return css.slice(start + selector.length + 2, end).trim();
}

const light = extractBlock(":root");
const dark = extractBlock(".dark");

const stylesheet = `/* Generated from @zelavis/ui app/styles.css. Do not edit. */
:root {
${light}
  color-scheme: light;
}

/* Framed pages cannot see the dashboard's theme class, so they follow the
   viewer's system preference. A page that wants to follow the dashboard's
   explicit choice can set data-theme on its own root. */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${dark}
    color-scheme: dark;
  }
}

:root[data-theme="dark"] {
${dark}
  color-scheme: dark;
}

* {
  box-sizing: border-box;
}

/* Any explicit \`display\` beats the \`hidden\` attribute's user-agent rule, so a
   page that styles an element as flex or grid silently un-hides it. Every page
   that toggles visibility hits this, so it is settled here once. */
[hidden] {
  display: none !important;
}

body {
  margin: 0;
  padding: 1.5rem;
  font-family: "Inter Variable", system-ui, -apple-system, "Segoe UI", sans-serif;
  font-size: 0.9375rem;
  line-height: 1.6;
  /* Transparent so the dashboard's own surface shows through the frame. */
  background: transparent;
  color: var(--foreground);
}

h1, h2, h3 { margin: 0 0 0.5rem; line-height: 1.25; font-weight: 600; }
h1 { font-size: 1.25rem; }
h2 { font-size: 1.0625rem; }
p { margin: 0 0 1rem; color: var(--muted-foreground); }
a { color: var(--primary); }

.zv-card {
  border: 1px solid var(--border);
  border-radius: 0.75rem;
  background: var(--card);
  color: var(--card-foreground);
  padding: 1rem 1.25rem;
}

.zv-stack { display: grid; gap: 0.75rem; }
.zv-row {
  display: flex;
  align-items: center;
  justify-content: space-between;
  gap: 1rem;
}

.zv-muted { color: var(--muted-foreground); font-size: 0.8125rem; }

.zv-badge {
  display: inline-block;
  padding: 0.125rem 0.5rem;
  border-radius: 999px;
  border: 1px solid var(--border);
  font-size: 0.75rem;
  color: var(--muted-foreground);
}

.zv-button {
  font: inherit;
  padding: 0.375rem 0.875rem;
  border-radius: 0.5rem;
  border: 1px solid transparent;
  background: var(--primary);
  color: var(--primary-foreground);
  cursor: pointer;
}

.zv-button:disabled { opacity: 0.5; cursor: default; }
.zv-button[data-variant="outline"] {
  background: transparent;
  color: var(--foreground);
  border-color: var(--border);
}
`;

writeFileSync(
  output,
  `/**
 * Generated by scripts/generate-service-page-styles.mjs. Do not edit.
 *
 * Regenerate with \`pnpm --filter @zelavis/ui build:service-page-styles\`.
 */
export const zelavisServicePageStylesheet = ${JSON.stringify(stylesheet)};
`,
);

console.log(`Wrote ${output}`);
